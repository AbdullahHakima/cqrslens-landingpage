interface Run {
  x: number;
  y: number;
  w: number;
}

function extractRuns(rows: readonly string[]): Run[] {
  const result: Run[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let end = x + 1;
        while (end < row.length && row[end] === '#') {
          end++;
        }
        result.push({ x, y, w: end - x });
        x = end;
      } else {
        x++;
      }
    }
  }
  return result;
}

const GLYPH_RUN_CACHE = new Map<string, readonly Run[]>();

function getGlyphRuns(ch: string, rows: readonly string[]): readonly Run[] {
  const cached = GLYPH_RUN_CACHE.get(ch);
  if (cached) return cached;
  const runs = extractRuns(rows);
  GLYPH_RUN_CACHE.set(ch, runs);
  return runs;
}

interface PixelWordmarkProps {
  text?: string;
  /** Optional multi-line display lockup rendered in one shared coordinate space so all lines scale identically */
  lines?: readonly string[];
  /** Target height per 10-row glyph line (CSS length or clamp() expression). Scales down proportionally when container is narrower. */
  glyphHeight?: string;
  className?: string;
  style?: React.CSSProperties;
  animateEntrance?: boolean;
  glyphOffset?: number;
}

export const PixelWordmark: React.FC<PixelWordmarkProps> = ({
  text,
  lines,
  glyphHeight,
  className = '',
  style,
  animateEntrance = false,
  glyphOffset = 0,
}) => {
  const layout = useMemo(() => {
    const resolvedLines = lines && lines.length > 0 ? lines : [text ?? ''];
    const letterGap = 2;
    const lineGap = 4;
    const rowHeight = 10;

    let maxWidth = 1;
    let runningGlyphIndex = glyphOffset;
    const items: Array<{
      index: number;
      xOffset: number;
      yOffset: number;
      runs: readonly Run[];
    }> = [];

    resolvedLines.forEach((rawLine, lineIdx) => {
      const upper = rawLine.toUpperCase();
      let cursor = 0;
      const yOffset = lineIdx * (rowHeight + lineGap);

      for (let i = 0; i < upper.length; i++) {
        const ch = upper[i];
        const glyph = STEPPED_GLYPHS[ch] ?? STEPPED_GLYPHS[' '];
        const width = glyph[0].length;
        if (ch !== ' ') {
          items.push({
            index: runningGlyphIndex,
            xOffset: cursor,
            yOffset,
            runs: getGlyphRuns(ch, glyph),
          });
        }
        runningGlyphIndex += 1;
        cursor += width + letterGap;
      }

      const lineWidth = Math.max(1, cursor - letterGap);
      if (lineWidth > maxWidth) {
        maxWidth = lineWidth;
      }
    });

    const totalHeight =
      resolvedLines.length * rowHeight + Math.max(0, resolvedLines.length - 1) * lineGap;

    return { totalWidth: maxWidth, totalHeight, items };
  }, [text, lines, glyphOffset]);

  const widthRatio = Number((layout.totalWidth / 10).toFixed(4));
  const computedStyle: React.CSSProperties | undefined = glyphHeight
    ? {
        width: `min(100%, calc(${glyphHeight} * ${widthRatio}))`,
        height: 'auto',
        ...style,
      }
    : style;

  return (
    <svg
      viewBox={`0 0 ${layout.totalWidth} ${layout.totalHeight}`}
      preserveAspectRatio="xMinYMid meet"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      style={computedStyle}
      className={`block max-w-full fill-current ${glyphHeight ? '' : 'w-auto'} ${className}`.trim()}
    >
      {layout.items.map((item) => (
        <g
          key={`${item.index}-${item.xOffset}-${item.yOffset}`}
          transform={`translate(${item.xOffset}, ${item.yOffset})`}
        >
          <g
            className={animateEntrance ? 'pixel-glyph-enter' : undefined}
            style={
              animateEntrance
                ? ({ '--glyph-index': item.index } as React.CSSProperties)
                : undefined
            }
          >
            {item.runs.map((run, rIdx) => (
              <rect key={rIdx} x={run.x} y={run.y} width={run.w} height={1} />
            ))}
          </g>
        </g>
      ))}
    </svg>
  );
};
